export const LAUNCH_PROFILE_LIST = Object.freeze(Object.values(DEFAULT_LAUNCH_PROFILES));

export const cloneLaunchProfile = value => JSON.parse(JSON.stringify(value));

export const normalizeLaunchProfile = (value, fallback = DEFAULT_LAUNCH_PROFILES[value?.interceptorSpecId]) => {
  const source = { ...fallback, ...value };
  const clamp = (number, minimum, maximum, defaultValue) => {
    const parsed = Number(number);
    return Number.isFinite(parsed) ? Math.max(minimum, Math.min(maximum, parsed)) : defaultValue;
  };
  const normalized = {
    ...source,
    id: fallback.id,
    platformId: fallback.platformId,
    launcherId: fallback.launcherId,
    interceptorSpecId: fallback.interceptorSpecId,
    systemName: fallback.systemName,
    launcherName: fallback.launcherName,
    missileName: fallback.missileName,
    launcherAssetId: fallback.launcherAssetId,
    missileAssetId: fallback.missileAssetId,
    launchMode: source.launchMode === LAUNCH_MODE.VERTICAL ? LAUNCH_MODE.VERTICAL : LAUNCH_MODE.INCLINED,
    launchPoints: [(source.launchPoints?.length ? source.launchPoints : fallback.launchPoints)[0]].map(point => ({
      id: 'launch-point',
      x: clamp(point.x, 0, 1, 0.5),
      y: clamp(point.y, 0, 1, 0.5),
      launchDirectionOffsetDeg: clamp(point.launchDirectionOffsetDeg, -180, 180, 0),
    })),
    preLaunchDelaySec: clamp(source.preLaunchDelaySec, 0, 5, fallback.preLaunchDelaySec),
    initialLaunchSpeedMps: clamp(source.initialLaunchSpeedMps, 1, 300, fallback.initialLaunchSpeedMps),
    initialLaunchAccelerationMps2: clamp(source.initialLaunchAccelerationMps2, 1, 400, fallback.initialLaunchAccelerationMps2),
    initialAccelerationDurationSec: clamp(source.initialAccelerationDurationSec, 0.1, 3, fallback.initialAccelerationDurationSec),
    guidanceEnableDelaySec: clamp(source.guidanceEnableDelaySec, 0, 4, fallback.guidanceEnableDelaySec),
    visualDepartureDurationSec: clamp(source.visualDepartureDurationSec, 0.1, 4, fallback.visualDepartureDurationSec),
    spriteRotationOffsetDeg: clamp(source.spriteRotationOffsetDeg, -360, 360, fallback.spriteRotationOffsetDeg),
    visualScale: clamp(source.visualScale, 0.25, 3, fallback.visualScale),
    mirrorX: Boolean(source.mirrorX),
    mirrorY: Boolean(source.mirrorY),
    orientLauncherToTarget: Boolean(source.orientLauncherToTarget),
    verticalDepartureDurationSec: clamp(source.verticalDepartureDurationSec, 0, 4, fallback.verticalDepartureDurationSec),
    verticalDepartureVisualDistance: clamp(source.verticalDepartureVisualDistance, 0, 120, fallback.verticalDepartureVisualDistance),
    initialTurnDelaySec: clamp(source.initialTurnDelaySec, 0, 4, fallback.initialTurnDelaySec),
    turnToTargetDurationSec: clamp(source.turnToTargetDurationSec, 0.1, 5, fallback.turnToTargetDurationSec),
  };
  delete normalized.launcherFootprintM;
  return normalized;
};
